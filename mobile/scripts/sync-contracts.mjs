// Embeds the reference programs of the Ting repository (its `programs`
// folder) so the app can derive their canonical ContractIds on any chain
// (wiki: programs). Run after the programs change:
//
//   npm run sync-contracts [-- <path of the ting repository>]   (default: ../../ting)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const dist = join(process.argv[2] ?? join(root, '..', '..', 'ting'), 'programs');
const names = ['policy-secp256k1', 'policy-p256', 'policy-multisig-secp256k1', 'id-registry', 'coin', 'batch'];

let out = '// Generated by scripts/sync-contracts.mjs from the Ting repository\'s programs. Do not edit.\n';
out += 'export const CONTRACT_CODE: Record<string, string> = {\n';
for (const name of names) {
  const bytes = readFileSync(join(dist, `${name}.wasm`));
  out += `  '${name}':\n    '${bytes.toString('base64')}',\n`;
}
out += '};\n';
const manifest = JSON.parse(readFileSync(join(dist, 'manifest.json'), 'utf8'));
out += 'export const CONTRACT_HASHES: Record<string, string> = {\n';
for (const entry of manifest) {
  if (names.includes(entry.name)) out += `  '${entry.name}': '${entry.code_hash}',\n`;
}
out += '};\n';
writeFileSync(join(root, 'src', 'chain', 'contracts.generated.ts'), out);
console.log(`embedded ${names.length} contracts`);
