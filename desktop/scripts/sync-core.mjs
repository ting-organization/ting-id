// The protocol formats and the app logic (node queries, signing, identity and
// coin state) live in the mobile app and are shared with this desktop app by
// copying: this script mirrors ../mobile/src/{chain,state,config}
// and src/ui/{describe,qrShape,coinFacts}.ts into src/core, rewriting module paths, and
// copies the interoperability and payment-code tests with the vectors and the
// logo (assets/logo/icon-rounded.svg as public/logo.svg). Edit
// the originals, then run
// `npm run sync-core`.
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const mobile = join(root, '..', 'mobile');
if (!existsSync(join(mobile, 'src', 'chain'))) {
  console.error(`mobile app not found next to this one (${mobile})`);
  process.exit(1);
}

const rewrites = [
  [/'@\/chain\//g, "'@/core/chain/"],
  [/'@\/state\//g, "'@/core/state/"],
  [/'@\/config\//g, "'@/core/config/"],
  [/'@\/ui\/describe'/g, "'@/core/describe'"],
  [/'@\/ui\/coinFacts'/g, "'@/core/coinFacts'"],
  [/from '\.\/components'/g, "from '@/platform/ui-types'"],
];

function copyFile(from, to, extra = []) {
  const rel = relative(mobile, from).replace(/\\/g, '/');
  let text = readFileSync(from, 'utf8');
  for (const [pattern, replacement] of [...rewrites, ...extra]) text = text.replace(pattern, replacement);
  const header = `// Generated by scripts/sync-core.mjs from mobile/${rel}; edit it there and run npm run sync-core.\n`;
  mkdirSync(dirname(to), { recursive: true });
  writeFileSync(to, from.endsWith('.json') ? text : header + text);
  return rel;
}

function copyDir(from, to) {
  const copied = [];
  for (const name of readdirSync(from)) {
    const src = join(from, name);
    if (statSync(src).isDirectory()) copied.push(...copyDir(src, join(to, name)));
    else if (/\.tsx?$/.test(name)) copied.push(copyFile(src, join(to, name)));
  }
  return copied;
}

const core = join(root, 'src', 'core');
rmSync(core, { recursive: true, force: true });
const copied = [
  ...copyDir(join(mobile, 'src', 'chain'), join(core, 'chain')),
  ...copyDir(join(mobile, 'src', 'state'), join(core, 'state')),
  ...copyDir(join(mobile, 'src', 'config'), join(core, 'config')),
  copyFile(join(mobile, 'src', 'ui', 'describe.ts'), join(core, 'describe.ts')),
  copyFile(join(mobile, 'src', 'ui', 'qrShape.ts'), join(core, 'qrShape.ts')),
  copyFile(join(mobile, 'src', 'ui', 'coinFacts.ts'), join(core, 'coinFacts.ts')),
  copyFile(join(mobile, 'tests', 'chain.test.ts'), join(root, 'tests', 'chain.test.ts'), [[/'\.\.\/src\/chain\//g, "'../src/core/chain/"]]),
  copyFile(join(mobile, 'tests', 'request.test.ts'), join(root, 'tests', 'request.test.ts'), [
    [/'\.\.\/src\/chain\//g, "'../src/core/chain/"],
    [/'\.\.\/src\/ui\/qrShape'/g, "'../src/core/qrShape'"],
  ]),
  copyFile(join(mobile, 'tests', 'vectors.json'), join(root, 'tests', 'vectors.json')),
];
mkdirSync(join(root, 'public'), { recursive: true });
copyFileSync(join(mobile, 'assets', 'logo', 'icon-rounded.svg'), join(root, 'public', 'logo.svg'));
copied.push('assets/logo/icon-rounded.svg');
console.log(`synced ${copied.length} files from mobile`);
